package pooMiniExercicioArrayList01.src.Program.Proces;

public class Item {

    //Atributos
    private String nome;
    private double preco;

    //Contrutor

    public Item(String nome, double preco){
        this.nome = nome;
        this.preco = preco;
    }

    public String getNome() {
        return nome;
    }

    public double getPreco() {
        return preco;
    }
}
